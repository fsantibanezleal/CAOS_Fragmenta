// Generates src/lib/contract.gen.ts from ../docs/contracts/api.openapi.json (ADR-0080 decision 2: the schema files
// are the single source of every contract; the TypeScript types are generated, never hand-written).
// `--check` generates in memory and fails when the committed file differs, so a schema change without a
// regeneration stops `npm run build` (the currency check; no CI job of its own, ADR-0074).
//
// The OpenAPI document references the schema files; each file keeps its shared definitions in `$defs`, as a
// self-contained JSON Schema must. openapi-typescript would render `$defs` as a property of every document type,
// so the files are inlined here first: every `$defs` entry becomes a component and its `#/$defs/<name>` references
// point at it. A name defined in several files must be defined identically to be one shared type; a name the files
// define differently (Fragmenta: `version` in the readiness file, `armProvenance` in the benchmark and models files)
// keeps the plain name in the files that share the most common definition and is renamed to `<Component><Name>` in
// each of the others, so every file keeps its own definition.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const here = dirname(fileURLToPath(import.meta.url));
const contracts = join(here, '..', '..', 'docs', 'contracts');
const target = join(here, '..', 'src', 'lib', 'contract.gen.ts');
const HEADER = '// GENERATED by frontend/scripts/gen-contract-types.mjs from docs/contracts/api.openapi.json. Do not edit.\n';

const readJSON = (path) => JSON.parse(readFileSync(path, 'utf8'));

/** A copy of `node` with every `#/$defs/<name>` reference pointed at the component `<name>` (or the one `rename` gives). */
function relink(node, rename = {}) {
  if (Array.isArray(node)) return node.map((n) => relink(n, rename));
  if (node === null || typeof node !== 'object') return node;
  const out = {};
  for (const [key, value] of Object.entries(node)) {
    out[key] = key === '$ref' && typeof value === 'string' && value.startsWith('#/$defs/')
      ? `#/components/schemas/${rename[value.slice('#/$defs/'.length)] ?? value.slice('#/$defs/'.length)}`
      : relink(value, rename);
  }
  return out;
}

/**
 * A copy of `node` where the length bounds of an array are dropped unless the array is a pair (minItems = maxItems = 2:
 * an interval or a range). openapi-typescript's `arrayLength` then types a pair as `[number, number]`, as the reader
 * needs it, and every other array, a vector indexed by a number or a list that may be long, as `T[]`; a vector of
 * seven typed as a seven-tuple, or `minItems: 1` as `[T, ...T[]]`, only gets in the way of indexing it in a loop.
 */
function pairsOnly(node) {
  if (Array.isArray(node)) return node.map(pairsOnly);
  if (node === null || typeof node !== 'object') return node;
  const pair = node.minItems === 2 && node.maxItems === 2;
  const out = {};
  for (const [key, value] of Object.entries(node)) {
    if ((key === 'minItems' || key === 'maxItems') && !pair) continue;
    out[key] = pairsOnly(value);
  }
  return out;
}

/** The component name `<Component><Name>` a definition takes when files define `name` differently. */
const qualified = (component, name) => `${component}${name[0].toUpperCase()}${name.slice(1)}`;

/** The OpenAPI document with every file reference of components.schemas inlined and its `$defs` hoisted. */
export function inlineDocument() {
  const doc = readJSON(join(contracts, 'api.openapi.json'));
  const schemas = doc.components.schemas;
  const files = [];
  for (const [component, schema] of Object.entries(schemas)) {
    if (typeof schema.$ref !== 'string' || schema.$ref.startsWith('#')) continue;
    const { $defs = {}, $schema: _dialect, $id: _id, ...body } = readJSON(join(contracts, schema.$ref));
    for (const defName of Object.keys($defs)) {
      if (defName in schemas) throw new Error(`$defs ${defName} of ${schema.$ref} collides with a component`);
    }
    files.push({ component, ref: schema.$ref, defs: $defs, body, rename: {} });
  }
  // A name is shared while every file that defines it defines it identically once its own references are linked; a
  // renamed definition can change what another definition means, so the comparison repeats until nothing changes.
  for (let changed = true; changed; ) {
    changed = false;
    const seen = {};
    for (const f of files) {
      for (const [defName, def] of Object.entries(f.defs)) {
        if (defName in f.rename) continue;
        (seen[defName] ??= []).push({ f, text: JSON.stringify(relink(def, f.rename)) });
      }
    }
    for (const [defName, uses] of Object.entries(seen)) {
      const counts = new Map();
      for (const { text } of uses) counts.set(text, (counts.get(text) ?? 0) + 1);
      if (counts.size > 1) {
        // the definition most files share (the first on a tie) keeps the plain name; each other file's is renamed
        const keeper = [...counts.entries()].reduce((best, e) => (e[1] > best[1] ? e : best))[0];
        for (const { f, text } of uses) if (text !== keeper) f.rename[defName] = qualified(f.component, defName);
        changed = true;
      }
    }
  }
  const hoisted = {};
  for (const f of files) {
    for (const [defName, def] of Object.entries(f.defs)) {
      const name = f.rename[defName] ?? defName;
      if (name in schemas) throw new Error(`$defs ${defName} of ${f.ref} collides with a component`);
      hoisted[name] = relink(def, f.rename);
    }
    schemas[f.component] = relink(f.body, f.rename);
  }
  Object.assign(schemas, hoisted);
  return doc;
}

const ast = await openapiTS(pairsOnly(inlineDocument()), { arrayLength: true });
const body = astToString(ast).replace(/\r\n/g, '\n').replace(/\s+$/, '');
const text = `${HEADER}${body}\n`;

if (process.argv.includes('--check')) {
  let current = null;
  try {
    current = readFileSync(target);
  } catch {
    // an absent file is not current
  }
  if (current === null || !current.equals(Buffer.from(text, 'utf8'))) {
    console.error('contract.gen.ts is not current: run npm run contracts:types');
    process.exit(1);
  }
  console.log('contract types: current');
} else {
  writeFileSync(target, text, 'utf8');
  console.log('contract types: wrote frontend/src/lib/contract.gen.ts');
}
