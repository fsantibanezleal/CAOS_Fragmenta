def arm_block(b: dict, arm: str) -> str:
    """The evidence for one arm, as it stands in the artifact: every protocol, both row sets."""
    R = b["protocols"]["random-8020"]["arms"][arm]["repeats"]
    D = b["protocols"]["dedup-random"]["arms"][arm]["repeats"]
    g = b["protocols"]["leave-one-site-out"]["arms"][arm]
    sa, sg = g["supports"]["all"], g["supports"]["geometry"]
    per = {k: v.get("rmse_m") for k, v in g["per_site"].items() if v.get("rmse_m") is not None}
    lines = [f"Evidence for **{NAMES[arm]}** in the committed benchmark (variance explained about the identity line):", ""]
    if R.get("n"):
        lines.append(
            f"- random 80/20, {b['n_repeats']} draws: median {f(R['median'])}, "
            f"5th to 95th percentile {f(R['p05'], 2)} to {f(R['p95'], 2)};"
        )
        lines.append(f"- deduplicated, {b['n_repeats']} draws: median {f(D.get('median'))};")
    else:
        lines.append("- random and deduplicated draws: abstains on every row;")
    abst = f", {g['n_abstained']} blasts abstained" if g.get("n_abstained") else ""
    n_geo = b["verdict"]["supports"]["geometry"]["n_blasts"]
    lines.append(
        f"- held out by site, every blast: {f(sa['score']['r2_identity'])} "
        f"(site-resampled 95 percent interval {iv(sa['interval_95'])}{abst});"
    )
    lines.append(
        f"- held out by site, the {n_geo} blasts with geometry: {f(sg['score']['r2_identity'])} ({iv(sg['interval_95'])});"
    )
    if per:
        worst = max(per, key=per.get)
        best = min(per, key=per.get)
        lines.append(
            f"- error by held-out campaign: lowest at {best} ({f(per[best])} m RMSE), highest at {worst} ({f(per[worst])} m)."
        )
    p = b["provenance"].get(arm, {})
    notes = []
    if p.get("in_sample_corpus"):
        notes.append("its coefficients were fitted by its source on this corpus, so no split hides a blast from it")
    if p.get("uses_site_constant"):
        notes.append("it reads a constant derived from the held-out site itself")
    if p.get("router_in_sample"):
        notes.append("it is routed by the published discriminant, which was fitted on this corpus")
    if notes:
        lines += ["", "Provenance: " + "; ".join(notes) + "."]
    return "\n".join(lines)


def blocks(b: dict) -> dict[str, str]:
    """Every fact block a hand-written page may embed, rendered from the artifact."""
    grouped = b["protocols"]["leave-one-site-out"]["arms"]
    out = {f"arm-{arm}": arm_block(b, arm) for arm in ORDER if arm in grouped}
    s = b["verdict"]["supports"]
    a, g = s["all"], s["geometry"]
    out["verdict"] = (
        f"Over every blast ({a['n_blasts']}), the best learned arm held out by site is {NAMES[a['best_learned_arm']]} at "
        f"{f(a['best_learned_r2_identity'])} ({iv(a['best_learned_interval_95'])}), and the criterion is "
        f"{'met' if a['generalises_across_sites'] else 'not met'}. Over the {g['n_blasts']} blasts with resolvable "
        f"geometry it is {NAMES[g['best_learned_arm']]} at {f(g['best_learned_r2_identity'])} "
        f"({iv(g['best_learned_interval_95'])}), {f(g['margin_over_null'])} above the null, and the criterion is "
        f"{'met' if g['generalises_across_sites'] else 'not met'}. The null's held-out predictions correlate with the "
        f"measurements at {f(a['null_pearson_r'], 2)}."
    )
    sw = b["network_seed_sweep"]
    out["seed-sweep"] = (
        f"Over {sw['n_seeds']} seeds the reproduced network explains {f(sw['min'])} to {f(sw['max'])} of the variance on "
        f"the 2012 hold-out (median {f(sw['median'])}); the published figure is {f(sw['published'])}, "
        f"{'above' if sw['published_above_every_seed'] else 'not above'} every seed."
    )
    tf = b["diagnostics"]["transfer_fit"]
    out["transfer-line"] = (
        f"Fitted on the {len(tf['fit_sites'])} sites with a recovered factor: ln A = {tf['intercept']:.4f} + "
        f"{tf['slope']:.4f} ln E. Each case refits it without its own site."
    )
    arms = b["published_reproduction"]["published_holdout_arms"]
    rows = [
        "| model, as printed in the 2012 paper | variance explained | squared correlation | RMSE, m |",
        "|---|---|---|---|",
    ]
    for k, n in (
        ("classical", "classical"),
        ("regression", "regression"),
        ("neural-net", "neural network"),
        ("null", "null, the training mean"),
    ):
        rows.append(
            f"| {n} | {f(arms[k].get('r2_identity'))} | {f(arms[k].get('pearson_r2'))} | {f(arms[k].get('rmse_m'), 4)} |"
        )
    out["holdout-2012"] = "\n".join(rows)
    L = b["protocols"]["leave-one-site-out"]["arms"]
    rows = [
        "| held-out campaign | E, GPa | A recovered for the site | A from the line on all sites | "
        "site-factor arm, RMSE m | transfer arm, RMSE m |",
        "|---|---|---|---|---|---|",
    ]
    for site in b["sites"]:
        m = b["site_meta"][site]
        a = L["kuznetsov"]["per_site"][site].get("rmse_m")
        t = L["kuznetsov-transfer"]["per_site"][site].get("rmse_m")
        rows.append(
            f"| {site} | {', '.join(str(e) for e in m['E_GPa'])} | "
            f"{'no geometry' if m['rock_factor_recovered'] is None else f(m['rock_factor_recovered'], 2)} | "
            f"{f(m['rock_factor_transfer'], 2)} | {'abstains' if a is None else f(a)} | {'abstains' if t is None else f(t)} |"
        )
    out["rock-routes"] = "\n".join(rows + [
        "",
        "The line column uses the fit on all nine sites with a recovered factor, for comparison; in the "
        "benchmark each held-out campaign is predicted by a line refitted without it.",
    ])
    pub = b["verdict"]["published_random_split_figures"]
    out["published-splits"] = "\n".join(
        f"- {NAMES.get(k, k)}: published {p['published']:.3f} on one random split; the reproduced draws have a median "
        f"of {f(p['median_draw'])}, and {round(p['share_of_draws_below'] * 100)} of 100 fall below the published figure."
        for k, p in pub.items()
    )
    return out


# The body is lazy and may not cross another opener, so an empty block followed by a second block is
# two blocks, not one block that swallowed the other.
BLOCK = re.compile(
    r"^(<!-- facts:([a-z0-9-]+) -->)\n(?:(?:(?!^<!-- facts:).)*?\n)??(<!-- /facts -->)$", re.S | re.M
)
OPENER = re.compile(r"^<!-- facts:", re.M)


def fill(text: str, facts: dict[str, str], where: str) -> str:
    """Replace the body of every fact block; an unknown key or an unclosed block fails."""

    def repl(m: re.Match) -> str:
        key = m.group(2)
        if key not in facts:
            raise SystemExit(f"{where}: unknown fact block '{key}'")
        return f"{m.group(1)}\n{facts[key]}\n{m.group(3)}"

    filled, n = BLOCK.subn(repl, text)
    if n != len(OPENER.findall(text)):
        raise SystemExit(f"{where}: a fact block is not closed by '<!-- /facts -->' on its own line")
    return filled


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    b = json.loads((DERIVED / "benchmark.json").read_text(encoding="utf-8"))
    index = json.loads((DERIVED / "manifests" / "index.json").read_text(encoding="utf-8"))
    stale = []
    rendered = pages(b, index)
    facts = blocks(b)
    for path in sorted(DOCS.rglob("*.md")):
        name = path.relative_to(DOCS).as_posix()
        if name in rendered:
            continue
        current = path.read_text(encoding="utf-8")
        if OPENER.search(current):
            rendered[name] = fill(current, facts, name)
    for name, text in rendered.items():
        path = DOCS / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
    if stale:
        print(f"out of date: {', '.join(stale)}; run python scripts/build_docs_results.py")
        return 1
    print("docs results: " + ("up to date" if args.check else "written"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
