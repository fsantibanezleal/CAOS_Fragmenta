             "", "The outcome the engine writes, verbatim:", "", f"> {v['outcome']}", "",
             "Arms in sample (fitted by their source on this corpus): " + ", ".join(f"{NAMES.get(a[0])} ({f(a[1])})" for a in v["in_sample_arms"]) + ".",
