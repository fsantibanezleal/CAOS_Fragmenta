#!/usr/bin/env python3
"""Generate the results pages of the docs wiki from the committed benchmark artifact.

    python scripts/build_docs_results.py          write docs/results.md and docs/results/*.md
    python scripts/build_docs_results.py --check  fail if a committed page is out of date

A results page that is typed by hand goes stale at the next bake, and a stale number in a wiki reads as
true. These pages are rendered from `data/derived/benchmark.json`, so every figure in them is the
artifact's; the test suite runs this script in check mode. The theory pages link here for numbers.

A hand-written page can also carry a fact block, which this script fills and checks the same way:

    <!-- facts:arm-kuznetsov -->
    (rendered from the artifact; anything typed here is replaced)
    <!-- /facts -->

The block keys are the ones `blocks()` returns. An unknown key fails, so a typo cannot leave a block
silently unfilled.
"""

