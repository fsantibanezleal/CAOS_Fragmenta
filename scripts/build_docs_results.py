# The body is lazy and may not cross another opener, so an empty block followed by a second block is
# two blocks, not one block that swallowed the other.
BLOCK = re.compile(
    r"^(<!-- facts:([a-z0-9-]+) -->)\n(?:(?:(?!^<!-- facts:).)*?\n)??(<!-- /facts -->)$", re.S | re.M
)
OPENER = re.compile(r"^<!-- facts:", re.M)


def fill(text: str, facts: dict[str, str], where: str) -> str:
    """Replace the body of every fact block; an unknown key or an unclosed block fails."""

    def repl(m: re.Match) -> str:
        key = m.group(2)
        if key not in facts:
            raise SystemExit(f"{where}: unknown fact block '{key}'")
        return f"{m.group(1)}\n{facts[key]}\n{m.group(3)}"

    filled, n = BLOCK.subn(repl, text)
    if n != len(OPENER.findall(text)):
        raise SystemExit(f"{where}: a fact block is not closed by '<!-- /facts -->' on its own line")
    return filled


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    b = json.loads((DERIVED / "benchmark.json").read_text(encoding="utf-8"))
    index = json.loads((DERIVED / "manifests" / "index.json").read_text(encoding="utf-8"))
    stale = []
    rendered = pages(b, index)
    facts = blocks(b, index)
    # The wiki, and the repository README, which states the result too.
    for path in [*sorted(DOCS.rglob("*.md")), ROOT / "README.md"]:
        name = Path(os.path.relpath(path, DOCS)).as_posix()
        if name in rendered:
            continue
        current = path.read_text(encoding="utf-8")
        if OPENER.search(current):
            rendered[name] = fill(current, facts, name)
    for name, text in rendered.items():
        path = DOCS / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
    if stale:
        print(f"out of date: {', '.join(stale)}; run python scripts/build_docs_results.py")
        return 1
    print("docs results: " + ("up to date" if args.check else "written"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
